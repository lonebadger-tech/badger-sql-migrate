using System.Data;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text.RegularExpressions;
using Badger.Trek.Core.Conversion;
using Badger.Trek.Core.Providers;
using Badger.Trek.Providers.SqlServer.Scripting;
using Microsoft.Data.SqlClient;

namespace Badger.Trek.Providers.SqlServer.Conversion;

/// <summary>
/// Reads tables with a forward-only reader and loads them with SqlBulkCopy (identity values kept, triggers not fired,
/// constraints checked afterwards). Spatial, hierarchyid and sql_variant values are read as text.
/// </summary>
public sealed partial class SqlServerDataTransfer : IDataTransfer
{
    private const int BatchSize = 5000;

    private static SqlConnection Connection(IDatabaseSession session) =>
        (session as SqlServerSession ?? throw new ArgumentException("Not a SQL Server session.", nameof(session))).Connection;

    private static string Name(PortableName table) => $"{Sql.Quote(table.Schema)}.{Sql.Quote(table.Name)}";

    public async Task<IReadOnlyList<TransferColumn>> ColumnsAsync(IDatabaseSession session, PortableName table, CancellationToken cancellationToken)
    {
        // Graph tables (and sys.columns.graph_type) arrived in SQL Server 2017; their internal columns are not copied.
        var graph = await SqlServerCompatibility.HasGraphTablesAsync(session, cancellationToken).ConfigureAwait(false);
        var rows = await session.QueryAsync($"""
            SELECT c.name, ts.name AS type_schema, t.name AS type_name, t.is_user_defined, c.max_length, c.precision, c.scale
            FROM sys.columns c
            JOIN sys.types t ON t.user_type_id = c.user_type_id
            JOIN sys.schemas ts ON ts.schema_id = t.schema_id
            WHERE c.object_id = OBJECT_ID(@name) AND c.is_computed = 0{(graph ? " AND c.graph_type IS NULL" : string.Empty)}
            ORDER BY c.column_id;
            """, new Dictionary<string, object?> { ["name"] = Name(table) }, cancellationToken).ConfigureAwait(false);
        return rows.Select(r => new TransferColumn((string)r["name"]!, SqlServerModel.TypeName((string)r["type_schema"]!, (string)r["type_name"]!, r["is_user_defined"] is true,
            System.Convert.ToInt32(r["max_length"], CultureInfo.InvariantCulture), System.Convert.ToInt32(r["precision"], CultureInfo.InvariantCulture), System.Convert.ToInt32(r["scale"], CultureInfo.InvariantCulture)))).ToList();
    }

    public async Task<long> CountAsync(IDatabaseSession session, PortableName table, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT COUNT_BIG(*) AS n FROM {Name(table)};", null, cancellationToken).ConfigureAwait(false);
        return System.Convert.ToInt64(rows[0]["n"], CultureInfo.InvariantCulture);
    }

    public async IAsyncEnumerable<object?[]> ReadAsync(IDatabaseSession session, PortableName table, IReadOnlyList<TransferColumn> columns, [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        var select = string.Join(", ", columns.Select(c => c.Type.ToLowerInvariant() switch
        {
            "geography" or "geometry" => $"{Sql.Quote(c.Name)}.STAsText()",
            "hierarchyid" => $"{Sql.Quote(c.Name)}.ToString()",
            "sql_variant" => $"CONVERT(nvarchar(max), {Sql.Quote(c.Name)})",
            _ => Sql.Quote(c.Name),
        }));
        await using var command = Connection(session).CreateCommand();
        command.CommandText = $"SELECT {select} FROM {Name(table)};";
        command.CommandTimeout = 0;
        await using var reader = await command.ExecuteReaderAsync(CommandBehavior.SequentialAccess, cancellationToken).ConfigureAwait(false);
        while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
        {
            var row = new object?[columns.Count];
            for (var i = 0; i < columns.Count; i++)
            {
                row[i] = await reader.IsDBNullAsync(i, cancellationToken).ConfigureAwait(false) ? null : reader.GetValue(i);
            }

            yield return row;
        }
    }

    public async Task<long> WriteAsync(IDatabaseSession session, PortableName table, IReadOnlyList<TransferColumn> columns, IAsyncEnumerable<object?[]> rows, CancellationToken cancellationToken)
    {
        // rowversion values are generated by the server and cannot be loaded.
        var keep = Enumerable.Range(0, columns.Count).Where(i => columns[i].Type is not ("timestamp" or "rowversion")).ToList();
        using var bulk = new SqlBulkCopy(Connection(session), SqlBulkCopyOptions.KeepIdentity | SqlBulkCopyOptions.KeepNulls, null)
        {
            DestinationTableName = Name(table),
            BatchSize = BatchSize,
            BulkCopyTimeout = 0,
        };
        using var data = new DataTable();
        foreach (var i in keep)
        {
            data.Columns.Add(columns[i].Name, typeof(object));
            bulk.ColumnMappings.Add(columns[i].Name, columns[i].Name);
        }

        long written = 0;
        await foreach (var row in rows.WithCancellation(cancellationToken).ConfigureAwait(false))
        {
            data.Rows.Add(keep.Select(i => Value(row[i], columns[i].Type)).ToArray());
            if (data.Rows.Count >= BatchSize)
            {
                await bulk.WriteToServerAsync(data, cancellationToken).ConfigureAwait(false);
                written += data.Rows.Count;
                data.Clear();
            }
        }

        if (data.Rows.Count > 0)
        {
            await bulk.WriteToServerAsync(data, cancellationToken).ConfigureAwait(false);
            written += data.Rows.Count;
        }

        return written;
    }

    /// <summary>Values from another vendor's driver, made acceptable to SqlBulkCopy for the column type.</summary>
    private static object Value(object? value, string type)
    {
        if (value is null)
        {
            return DBNull.Value;
        }

        var t = type.ToLowerInvariant();
        return value switch
        {
            DateTime d when t.StartsWith("datetimeoffset", StringComparison.Ordinal) => new DateTimeOffset(d.Kind == DateTimeKind.Unspecified ? DateTime.SpecifyKind(d, DateTimeKind.Utc) : d.ToUniversalTime()),
            DateTimeOffset o when t.StartsWith("datetime2", StringComparison.Ordinal) || t is "datetime" or "smalldatetime" => o.UtcDateTime,
            DateOnly d => d.ToDateTime(TimeOnly.MinValue),
            TimeOnly time => time.ToTimeSpan(),
            _ when t.StartsWith("nvarchar", StringComparison.Ordinal) || t.StartsWith("varchar", StringComparison.Ordinal) || t.StartsWith("nchar", StringComparison.Ordinal) || t.StartsWith("char", StringComparison.Ordinal)
                => value is string s ? s : System.Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty,
            _ => value,
        };
    }

    public async Task TruncateAsync(IDatabaseSession session, IReadOnlyList<PortableName> tables, CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            await session.ExecuteAsync($"ALTER TABLE {Name(table)} NOCHECK CONSTRAINT ALL;", null, cancellationToken).ConfigureAwait(false);
        }

        foreach (var table in tables)
        {
            await session.ExecuteAsync($"DELETE FROM {Name(table)};", null, cancellationToken).ConfigureAwait(false);
        }
    }

    public Task BeginLoadAsync(IDatabaseSession session, IReadOnlyList<PortableName> tables, CancellationToken cancellationToken) => Task.CompletedTask;

    public async Task EndLoadAsync(IDatabaseSession session, IReadOnlyList<PortableName> tables, CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            // Bulk copy left constraints unchecked; check them now so they are trusted again.
            await session.ExecuteAsync($"ALTER TABLE {Name(table)} WITH CHECK CHECK CONSTRAINT ALL;", null, cancellationToken).ConfigureAwait(false);
            var identity = await session.QueryAsync("SELECT 1 AS x FROM sys.identity_columns WHERE object_id = OBJECT_ID(@name);", new Dictionary<string, object?> { ["name"] = Name(table) }, cancellationToken).ConfigureAwait(false);
            if (identity.Count > 0)
            {
                await session.ExecuteAsync($"DBCC CHECKIDENT (N'{Name(table).Replace("'", "''", StringComparison.Ordinal)}') WITH NO_INFOMSGS;", null, cancellationToken).ConfigureAwait(false);
            }
        }

        // Sequences behind column defaults: move them past the loaded values.
        var defaults = await session.QueryAsync("""
            SELECT s.name AS table_schema, o.name AS table_name, c.name AS column_name, dc.definition
            FROM sys.default_constraints dc
            JOIN sys.objects o ON o.object_id = dc.parent_object_id
            JOIN sys.schemas s ON s.schema_id = o.schema_id
            JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id
            WHERE dc.definition LIKE '%NEXT VALUE FOR%';
            """, null, cancellationToken).ConfigureAwait(false);
        foreach (var d in defaults)
        {
            var table = new PortableName((string)d["table_schema"]!, (string)d["table_name"]!);
            if (!tables.Any(t => t.Key == table.Key) || SequenceRegex().Match((string)d["definition"]!) is not { Success: true } m)
            {
                continue;
            }

            var max = await session.QueryAsync($"SELECT MAX({Sql.Quote((string)d["column_name"]!)}) AS m FROM {Name(table)};", null, cancellationToken).ConfigureAwait(false);
            if (max[0]["m"] is not { } value)
            {
                continue;
            }

            // Take values with sp_sequence_get_range until the next one is past the loaded maximum. ALTER SEQUENCE
            // RESTART WITH would also do it, but it rewrites the sequence's start value, which is part of its definition
            // and of the schema fingerprint, so trek verify would report drift.
            var sequence = m.Groups["seq"].Value;
            var state = (await session.QueryAsync(
                "SELECT CAST(start_value AS bigint) AS start_value, CAST(increment AS bigint) AS increment, CAST(last_used_value AS bigint) AS last_used FROM sys.sequences WHERE object_id = OBJECT_ID(@name);",
                new Dictionary<string, object?> { ["name"] = sequence }, cancellationToken).ConfigureAwait(false)).FirstOrDefault();
            if (state is null || System.Convert.ToInt64(state["increment"], CultureInfo.InvariantCulture) <= 0)
            {
                continue;
            }

            var increment = System.Convert.ToInt64(state["increment"], CultureInfo.InvariantCulture);
            var nextValue = state["last_used"] is { } used
                ? System.Convert.ToInt64(used, CultureInfo.InvariantCulture) + increment
                : System.Convert.ToInt64(state["start_value"], CultureInfo.InvariantCulture);
            var loaded = System.Convert.ToInt64(value, CultureInfo.InvariantCulture);
            if (nextValue <= loaded)
            {
                var count = ((loaded - nextValue) / increment) + 1;
                await session.ExecuteAsync(
                    "DECLARE @first sql_variant; EXEC sys.sp_sequence_get_range @sequence_name = @name, @range_size = @count, @range_first_value = @first OUTPUT;",
                    new Dictionary<string, object?> { ["name"] = sequence, ["count"] = count }, cancellationToken).ConfigureAwait(false);
            }
        }
    }

    [GeneratedRegex(@"NEXT\s+VALUE\s+FOR\s+(?<seq>(?:\[[^\]]+\]|\w+)(?:\.(?:\[[^\]]+\]|\w+))?)", RegexOptions.IgnoreCase)]
    private static partial Regex SequenceRegex();
}

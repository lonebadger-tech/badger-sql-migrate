using System.Globalization;
using System.Text.RegularExpressions;
using Badger.Trek.Core.Plan;

namespace Badger.Trek.Core.Import;

public sealed record EfImportOptions
{
    /// <summary>
    /// The SQL 'dotnet ef migrations script' wrote (every migration, without --idempotent), for SQL Server,
    /// PostgreSQL or SQLite.
    /// </summary>
    public required string UpScript { get; init; }

    /// <summary>
    /// Optional: 'dotnet ef migrations script &lt;last migration&gt; 0', every migration's Down() in reverse order.
    /// Without it, every change is !irreversible.
    /// </summary>
    public string? DownScript { get; init; }

    /// <summary>Where the scripts came from, for messages.</summary>
    public string Source { get; init; } = "the EF Core script";
}

/// <summary>
/// Converts Entity Framework Core migrations into trek's layout, from the scripts 'dotnet ef migrations script'
/// writes (EF Core 10). EF ends each migration with an INSERT into __EFMigrationsHistory (and each Down() with a
/// DELETE from it); everything since the previous one is that migration. Each migration becomes a change, in order,
/// named after the migration ("20261120131340_AddBlogUrl" becomes add-blog-url) with the note "ef &lt;migration id&gt;",
/// which 'trek baseline --from ef' matches against a database's __EFMigrationsHistory. trek runs each change in a
/// transaction of its own, so EF's BEGIN/START TRANSACTION and COMMIT, the history table and its rows are left out.
/// </summary>
public static partial class EfImporter
{
    public const string Tool = "EF";

    public const string HistoryTable = "__EFMigrationsHistory";

    /// <summary>The provider the script was written for: sqlserver, postgresql or sqlite.</summary>
    public static string DetectProvider(string script) =>
        script.Contains("[__EFMigrationsHistory]", StringComparison.Ordinal) ? "sqlserver"
        : StartTransactionRegex().IsMatch(script) || script.Contains("GENERATED BY DEFAULT AS IDENTITY", StringComparison.Ordinal) ? "postgresql"
        : "sqlite";

    public static ImportedProject Import(EfImportOptions options)
    {
        if (IdempotentRegex().IsMatch(options.UpScript))
        {
            throw new MigrationException($"{options.Source} was written with --idempotent: every statement checks __EFMigrationsHistory first. Write it without: dotnet ef migrations script -o up.sql");
        }

        var ups = Split(options.UpScript, InsertRegex());
        if (ups.Migrations.Count == 0)
        {
            throw new MigrationException($"{options.Source} has no migrations: it should be the output of 'dotnet ef migrations script', with an INSERT INTO __EFMigrationsHistory after each migration.");
        }

        var downs = options.DownScript is null ? null : Split(options.DownScript, DeleteRegex());
        var result = new ImportedProject { Tool = Tool };
        if (ups.Trailing.Length > 0)
        {
            result.Warnings.Add($"{options.Source}: SQL after the last migration was left out: {Shorten(ups.Trailing)}");
        }

        if (options.DownScript is null)
        {
            result.Warnings.Add("No down script: every change is !irreversible. Write one with 'dotnet ef migrations script <last migration> 0 -o down.sql' and import again with --down.");
        }

        foreach (var (id, deploy) in ups.Migrations)
        {
            var name = result.UniqueName(Words(MigrationName(id)), "migration", id.Split('_')[0]);
            var flags = ChangeFlags.None;
            string? revert = null;
            if (downs is not null)
            {
                revert = downs.Migrations.FirstOrDefault(d => d.Id == id).Sql;
                if (revert is null)
                {
                    result.Warnings.Add($"{name} ({id}): the down script has no Down() for it; the change is !irreversible.");
                }
            }

            if (revert is null)
            {
                flags |= ChangeFlags.Irreversible;
            }

            if (ForeignKeysPragmaRegex().IsMatch(deploy) || (revert is not null && ForeignKeysPragmaRegex().IsMatch(revert)))
            {
                // EF rebuilds SQLite tables with foreign keys switched off between its own transactions, which only
                // works outside a transaction.
                flags |= ChangeFlags.NoTransaction;
                result.Warnings.Add($"{name} ({id}): EF rebuilds a SQLite table with PRAGMA foreign_keys switched off, which does nothing inside a transaction, so the change is !notx and not atomic.");
            }

            result.Changes.Add(new ImportedChange(name, result.EscapeLiteral(deploy, id), revert is null ? null : result.EscapeLiteral(revert, id), flags, $"ef {id}", id)
            {
                PlannedAt = Timestamp(id),
            });
        }

        if (downs is not null)
        {
            foreach (var extra in downs.Migrations.Where(d => ups.Migrations.All(u => u.Id != d.Id)))
            {
                result.Warnings.Add($"The down script reverts {extra.Id}, which the up script does not have; left out.");
            }
        }

        return result;
    }

    /// <summary>The migration's own name: "20261120131340_AddBlogUrl" -> "AddBlogUrl".</summary>
    public static string MigrationName(string id) => id.IndexOf('_', StringComparison.Ordinal) is var i and > 0 ? id[(i + 1)..] : id;

    private sealed record SplitScript(List<(string Id, string Sql)> Migrations, string Trailing);

    /// <summary>Cuts the script at each history row statement; drops transaction control and the history table.</summary>
    private static SplitScript Split(string script, Regex boundary)
    {
        var text = script.TrimStart('﻿').Replace("\r\n", "\n", StringComparison.Ordinal);
        text = HistoryTableRegex().Replace(text, string.Empty);
        var migrations = new List<(string Id, string Sql)>();
        var start = 0;
        foreach (Match m in boundary.Matches(text))
        {
            migrations.Add((m.Groups["id"].Value, Clean(text[start..m.Index])));
            start = m.Index + m.Length;
        }

        return new SplitScript(migrations, Clean(text[start..]));
    }

    private static string Clean(string sql)
    {
        var lines = sql.Split('\n').Where(l => !TransactionLineRegex().IsMatch(l)).ToList();

        // GO separators and blank lines at either end belong to the statements that were removed.
        static bool Edge(string l) => l.Trim().Length == 0 || l.Trim().Equals("GO", StringComparison.OrdinalIgnoreCase);
        while (lines.Count > 0 && Edge(lines[0]))
        {
            lines.RemoveAt(0);
        }

        while (lines.Count > 0 && Edge(lines[^1]))
        {
            lines.RemoveAt(lines.Count - 1);
        }

        // Runs of blank lines (left where COMMIT/BEGIN lines were) become one.
        var output = new List<string>();
        foreach (var line in lines)
        {
            if (line.Trim().Length == 0 && output.Count > 0 && output[^1].Trim().Length == 0)
            {
                continue;
            }

            output.Add(line.TrimEnd());
        }

        return output.Count == 0 ? string.Empty : string.Join('\n', output) + "\n";
    }

    private static string Words(string pascal) => PascalRegex().Replace(pascal, " ");

    private static DateTimeOffset? Timestamp(string id) =>
        DateTime.TryParseExact(id.Split('_')[0], "yyyyMMddHHmmss", CultureInfo.InvariantCulture, DateTimeStyles.AdjustToUniversal | DateTimeStyles.AssumeUniversal, out var at)
            ? new DateTimeOffset(at, TimeSpan.Zero)
            : null;

    private static string Shorten(string text)
    {
        var flat = Regex.Replace(text, @"\s+", " ").Trim();
        return flat.Length > 100 ? flat[..97] + "..." : flat;
    }

    [GeneratedRegex(@"INSERT\s+INTO\s+[\[""]?__EFMigrationsHistory[\]""]?\s*\([^)]*\)\s*VALUES\s*\(\s*N?'(?<id>[^']+)'\s*,\s*N?'[^']*'\s*\)\s*;", RegexOptions.IgnoreCase)]
    private static partial Regex InsertRegex();

    [GeneratedRegex(@"DELETE\s+FROM\s+[\[""]?__EFMigrationsHistory[\]""]?\s+WHERE\s+[\[""]?MigrationId[\]""]?\s*=\s*N?'(?<id>[^']+)'\s*;", RegexOptions.IgnoreCase)]
    private static partial Regex DeleteRegex();

    /// <summary>The history table EF creates first: SQL Server's IF OBJECT_ID ... BEGIN CREATE TABLE ... END; (and its GO), or CREATE TABLE IF NOT EXISTS.</summary>
    [GeneratedRegex(@"IF\s+OBJECT_ID\(N'\[__EFMigrationsHistory\]'\)\s+IS\s+NULL\s+BEGIN\s+CREATE\s+TABLE\s+\[__EFMigrationsHistory\].*?\n\s*END;\s*\n(?:\s*GO\s*\n)?|CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+""__EFMigrationsHistory""\s*\(.*?\n\);\s*\n", RegexOptions.IgnoreCase | RegexOptions.Singleline)]
    private static partial Regex HistoryTableRegex();

    [GeneratedRegex(@"^\s*(?:BEGIN\s+TRANSACTION|START\s+TRANSACTION|COMMIT)\s*;\s*$", RegexOptions.IgnoreCase)]
    private static partial Regex TransactionLineRegex();

    [GeneratedRegex(@"^\s*START\s+TRANSACTION\s*;", RegexOptions.IgnoreCase | RegexOptions.Multiline)]
    private static partial Regex StartTransactionRegex();

    [GeneratedRegex(@"IF\s+NOT\s+EXISTS\s*\(\s*SELECT\s+\*\s+FROM\s+[\[""]?__EFMigrationsHistory|\bDO\s+\$EF\$", RegexOptions.IgnoreCase)]
    private static partial Regex IdempotentRegex();

    [GeneratedRegex(@"^\s*PRAGMA\s+foreign_keys\s*=", RegexOptions.IgnoreCase | RegexOptions.Multiline)]
    private static partial Regex ForeignKeysPragmaRegex();

    [GeneratedRegex(@"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")]
    private static partial Regex PascalRegex();
}

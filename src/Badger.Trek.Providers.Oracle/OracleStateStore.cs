using System.Globalization;
using System.Text.RegularExpressions;
using Badger.Trek.Core;
using Badger.Trek.Core.Providers;

namespace Badger.Trek.Providers.Oracle;

/// <summary>
/// The trek journal in Oracle. A schema is a user, and creating one needs privileges a deploy login rarely has, so the
/// state schema name becomes a table prefix in the schema trek deploys to: TREK_META, TREK_CHANGES, TREK_REPEATABLES,
/// TREK_EVENTS, TREK_SCHEMA_SNAPSHOTS (and TREK_LOCK for the deploy lock). Scripts are CLOBs, timestamps TIMESTAMP(6)
/// in UTC, flags NUMBER(1). Oracle stores an empty string as NULL, so text read back as NULL becomes "" where the
/// journal requires a value.
/// </summary>
public sealed partial class OracleStateStore : IStateStore
{
    public const int StateVersion = 1;

    /// <summary>The table the deploy lock holds a row of; not part of <see cref="StateTables.Names"/>.</summary>
    public const string LockTable = "lock";

    public string MoveScript(string from, string to)
    {
        // The lock table holds no history: the old one is dropped (the new one is created when a deploy first locks).
        var (f, t) = (Prefix(from), Prefix(to));
        return "BEGIN\n"
            + string.Join("\n", StateTables.Names.Select(n => $"  EXECUTE IMMEDIATE 'ALTER TABLE {f}{n.ToUpperInvariant()} RENAME TO {t}{n.ToUpperInvariant()}';"))
            + $"\n  BEGIN\n    EXECUTE IMMEDIATE 'DROP TABLE {f}{LockTable.ToUpperInvariant()} PURGE';\n  EXCEPTION\n    WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;\n  END;\nEND;";
    }

    public async Task<bool> ExistsAsync(IDatabaseSession session, string schema, CancellationToken cancellationToken) =>
        await TableExistsAsync(session, Prefix(schema) + "CHANGES", cancellationToken).ConfigureAwait(false);

    internal static async Task<bool> TableExistsAsync(IDatabaseSession session, string table, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync(
            "SELECT COUNT(*) AS n FROM all_tables WHERE owner = :owner AND table_name = :name",
            new Dictionary<string, object?> { ["owner"] = Owner(session), ["name"] = table },
            cancellationToken).ConfigureAwait(false);
        return Convert.ToInt64(rows[0]["n"], CultureInfo.InvariantCulture) > 0;
    }

    public async Task EnsureCreatedAsync(IDatabaseSession session, string schema, CancellationToken cancellationToken)
    {
        var p = Prefix(schema);
        var q = Qualifier(session);
        (string Table, string Ddl)[] tables =
        [
            ("META", $"""
            CREATE TABLE {q}{p}META (
                meta_key VARCHAR2(128 CHAR) NOT NULL PRIMARY KEY,
                meta_value CLOB)
            """),
            ("CHANGES", $"""
            CREATE TABLE {q}{p}CHANGES (
                seq NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(255 CHAR) NOT NULL UNIQUE,
                script_hash VARCHAR2(128 CHAR) NOT NULL,
                chain_id VARCHAR2(128 CHAR) NOT NULL,
                deploy_script CLOB,
                revert_script CLOB,
                verify_script CLOB,
                flags NUMBER(10) NOT NULL,
                deployed_at TIMESTAMP(6) NOT NULL,
                deployed_by VARCHAR2(255 CHAR),
                host VARCHAR2(255 CHAR),
                tool_version VARCHAR2(64 CHAR),
                duration_ms NUMBER(19) NOT NULL,
                applied_out_of_order NUMBER(1) NOT NULL,
                baselined NUMBER(1) NOT NULL,
                rendered_hash VARCHAR2(128 CHAR),
                rendered_revert_hash VARCHAR2(128 CHAR))
            """),
            ("REPEATABLES", $"""
            CREATE TABLE {q}{p}REPEATABLES (
                name VARCHAR2(512 CHAR) NOT NULL PRIMARY KEY,
                hash VARCHAR2(128 CHAR) NOT NULL,
                script CLOB,
                previous_hash VARCHAR2(128 CHAR),
                previous_script CLOB,
                applied_at TIMESTAMP(6) NOT NULL,
                applied_by VARCHAR2(255 CHAR))
            """),
            ("EVENTS", $"""
            CREATE TABLE {q}{p}EVENTS (
                id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind VARCHAR2(32 CHAR) NOT NULL,
                name VARCHAR2(512 CHAR) NOT NULL,
                script_hash VARCHAR2(128 CHAR),
                chain_id VARCHAR2(128 CHAR),
                message CLOB,
                event_at TIMESTAMP(6) NOT NULL,
                actor VARCHAR2(255 CHAR),
                host VARCHAR2(255 CHAR),
                tool_version VARCHAR2(64 CHAR),
                environment VARCHAR2(255 CHAR))
            """),
            ("SCHEMA_SNAPSHOTS", $"""
            CREATE TABLE {q}{p}SCHEMA_SNAPSHOTS (
                id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                fingerprint VARCHAR2(128 CHAR) NOT NULL,
                dump CLOB,
                captured_at TIMESTAMP(6) NOT NULL,
                head_chain_id VARCHAR2(128 CHAR))
            """),
        ];
        foreach (var (table, ddl) in tables)
        {
            if (!await TableExistsAsync(session, p + table, cancellationToken).ConfigureAwait(false))
            {
                await session.ExecuteAsync(ddl, null, cancellationToken).ConfigureAwait(false);
            }
        }

        var version = await GetMetaAsync(session, schema, "state_version", cancellationToken).ConfigureAwait(false);
        if (version is null)
        {
            await SetMetaAsync(session, schema, "state_version", StateVersion.ToString(CultureInfo.InvariantCulture), cancellationToken).ConfigureAwait(false);
        }
        else if (int.Parse(version, CultureInfo.InvariantCulture) > StateVersion)
        {
            throw new MigrationException($"The trek state tables ({p}*) were created by a newer version of Badger Trek (state version {version}). Upgrade the tool.");
        }
    }

    public async Task<string?> GetMetaAsync(IDatabaseSession session, string schema, string key, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT meta_value FROM {T(session, schema, "META")} WHERE meta_key = :meta_key", new Dictionary<string, object?> { ["meta_key"] = key }, cancellationToken).ConfigureAwait(false);
        return rows.Count == 0 ? null : (string?)rows[0]["meta_value"] ?? string.Empty;
    }

    public Task SetMetaAsync(IDatabaseSession session, string schema, string key, string value, CancellationToken cancellationToken) =>
        session.ExecuteAsync(
            $"""
            MERGE INTO {T(session, schema, "META")} t
            USING (SELECT :meta_key AS k FROM dual) s ON (t.meta_key = s.k)
            WHEN MATCHED THEN UPDATE SET t.meta_value = :meta_value
            WHEN NOT MATCHED THEN INSERT (meta_key, meta_value) VALUES (:meta_key, :meta_value)
            """,
            new Dictionary<string, object?> { ["meta_key"] = key, ["meta_value"] = value },
            cancellationToken);

    public async Task<IReadOnlyList<AppliedChange>> GetAppliedChangesAsync(IDatabaseSession session, string schema, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT * FROM {T(session, schema, "CHANGES")} ORDER BY seq", null, cancellationToken).ConfigureAwait(false);
        return rows.Select(r => new AppliedChange
        {
            Sequence = Long(r["seq"]),
            Name = (string)r["name"]!,
            ScriptHash = (string)r["script_hash"]!,
            ChainId = (string)r["chain_id"]!,
            DeployScript = Text(r["deploy_script"]),
            RevertScript = (string?)r["revert_script"],
            VerifyScript = (string?)r["verify_script"],
            Flags = (int)Long(r["flags"]),
            DeployedAtUtc = Utc(r["deployed_at"]),
            DeployedBy = Text(r["deployed_by"]),
            Host = Text(r["host"]),
            ToolVersion = Text(r["tool_version"]),
            DurationMs = Long(r["duration_ms"]),
            AppliedOutOfOrder = Long(r["applied_out_of_order"]) != 0,
            Baselined = Long(r["baselined"]) != 0,
            RenderedHash = (string?)r["rendered_hash"],
            RenderedRevertHash = (string?)r["rendered_revert_hash"],
        }).ToList();
    }

    public Task InsertChangeAsync(IDatabaseSession session, string schema, AppliedChange change, CancellationToken cancellationToken) =>
        session.ExecuteAsync($"""
            INSERT INTO {T(session, schema, "CHANGES")}
                (name, script_hash, chain_id, deploy_script, revert_script, verify_script, flags, deployed_at, deployed_by, host,
                 tool_version, duration_ms, applied_out_of_order, baselined, rendered_hash, rendered_revert_hash)
            VALUES
                (:name, :script_hash, :chain_id, :deploy_script, :revert_script, :verify_script, :flags, :deployed_at, :deployed_by, :host,
                 :tool_version, :duration_ms, :applied_out_of_order, :baselined, :rendered_hash, :rendered_revert_hash)
            """, ChangeParameters(change), cancellationToken);

    public Task UpdateChangeAsync(IDatabaseSession session, string schema, AppliedChange change, CancellationToken cancellationToken) =>
        session.ExecuteAsync($"""
            UPDATE {T(session, schema, "CHANGES")}
               SET script_hash = :script_hash, chain_id = :chain_id, deploy_script = :deploy_script, revert_script = :revert_script,
                   verify_script = :verify_script, flags = :flags, rendered_hash = :rendered_hash, rendered_revert_hash = :rendered_revert_hash
             WHERE name = :name
            """, ChangeParameters(change), cancellationToken);

    public Task DeleteChangeAsync(IDatabaseSession session, string schema, string name, CancellationToken cancellationToken) =>
        session.ExecuteAsync($"DELETE FROM {T(session, schema, "CHANGES")} WHERE name = :name", new Dictionary<string, object?> { ["name"] = name }, cancellationToken);

    public async Task<IReadOnlyList<AppliedRepeatable>> GetRepeatablesAsync(IDatabaseSession session, string schema, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT * FROM {T(session, schema, "REPEATABLES")} ORDER BY name", null, cancellationToken).ConfigureAwait(false);
        return rows.Select(r => new AppliedRepeatable
        {
            Name = (string)r["name"]!,
            Hash = (string)r["hash"]!,
            Script = Text(r["script"]),
            PreviousHash = (string?)r["previous_hash"],
            PreviousScript = (string?)r["previous_script"],
            AppliedAtUtc = Utc(r["applied_at"]),
            AppliedBy = Text(r["applied_by"]),
        }).ToList();
    }

    public Task UpsertRepeatableAsync(IDatabaseSession session, string schema, AppliedRepeatable repeatable, CancellationToken cancellationToken) =>
        session.ExecuteAsync($"""
            MERGE INTO {T(session, schema, "REPEATABLES")} t
            USING (SELECT :name AS n FROM dual) s ON (t.name = s.n)
            WHEN MATCHED THEN UPDATE SET t.hash = :hash, t.script = :script, t.previous_hash = :previous_hash,
                t.previous_script = :previous_script, t.applied_at = :applied_at, t.applied_by = :applied_by
            WHEN NOT MATCHED THEN INSERT (name, hash, script, previous_hash, previous_script, applied_at, applied_by)
                VALUES (:name, :hash, :script, :previous_hash, :previous_script, :applied_at, :applied_by)
            """,
            new Dictionary<string, object?>
            {
                ["name"] = repeatable.Name,
                ["hash"] = repeatable.Hash,
                ["script"] = repeatable.Script,
                ["previous_hash"] = repeatable.PreviousHash,
                ["previous_script"] = repeatable.PreviousScript,
                ["applied_at"] = repeatable.AppliedAtUtc,
                ["applied_by"] = repeatable.AppliedBy,
            },
            cancellationToken);

    public Task AppendEventAsync(IDatabaseSession session, string schema, MigrationEvent migrationEvent, CancellationToken cancellationToken) =>
        session.ExecuteAsync($"""
            INSERT INTO {T(session, schema, "EVENTS")} (kind, name, script_hash, chain_id, message, event_at, actor, host, tool_version, environment)
            VALUES (:kind, :name, :script_hash, :chain_id, :message, :event_at, :actor, :host, :tool_version, :environment)
            """,
            new Dictionary<string, object?>
            {
                ["kind"] = migrationEvent.Kind.ToString().ToLowerInvariant(),
                ["name"] = migrationEvent.Name,
                ["script_hash"] = migrationEvent.ScriptHash,
                ["chain_id"] = migrationEvent.ChainId,
                ["message"] = migrationEvent.Message,
                ["event_at"] = migrationEvent.AtUtc,
                ["actor"] = migrationEvent.Actor,
                ["host"] = migrationEvent.Host,
                ["tool_version"] = migrationEvent.ToolVersion,
                ["environment"] = migrationEvent.Environment,
            },
            cancellationToken);

    public async Task<IReadOnlyList<MigrationEvent>> GetEventsAsync(IDatabaseSession session, string schema, int limit, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT * FROM {T(session, schema, "EVENTS")} ORDER BY id DESC FETCH FIRST :limit ROWS ONLY", new Dictionary<string, object?> { ["limit"] = limit }, cancellationToken).ConfigureAwait(false);
        return rows.Select(r => new MigrationEvent
        {
            Id = Long(r["id"]),
            Kind = Enum.Parse<MigrationEventKind>((string)r["kind"]!, ignoreCase: true),
            Name = (string)r["name"]!,
            ScriptHash = (string?)r["script_hash"],
            ChainId = (string?)r["chain_id"],
            Message = (string?)r["message"],
            AtUtc = Utc(r["event_at"]),
            Actor = Text(r["actor"]),
            Host = Text(r["host"]),
            ToolVersion = Text(r["tool_version"]),
            Environment = (string?)r["environment"],
        }).ToList();
    }

    public Task InsertSchemaSnapshotAsync(IDatabaseSession session, string schema, SchemaSnapshot snapshot, CancellationToken cancellationToken) =>
        session.ExecuteAsync(
            $"INSERT INTO {T(session, schema, "SCHEMA_SNAPSHOTS")} (fingerprint, dump, captured_at, head_chain_id) VALUES (:fingerprint, :dump, :captured_at, :head_chain_id)",
            new Dictionary<string, object?>
            {
                ["fingerprint"] = snapshot.Fingerprint,
                ["dump"] = snapshot.Dump,
                ["captured_at"] = snapshot.CapturedAtUtc,
                ["head_chain_id"] = snapshot.HeadChainId,
            },
            cancellationToken);

    public async Task<SchemaSnapshot?> GetLatestSchemaSnapshotAsync(IDatabaseSession session, string schema, CancellationToken cancellationToken)
    {
        var rows = await session.QueryAsync($"SELECT * FROM {T(session, schema, "SCHEMA_SNAPSHOTS")} ORDER BY id DESC FETCH FIRST 1 ROWS ONLY", null, cancellationToken).ConfigureAwait(false);
        if (rows.Count == 0)
        {
            return null;
        }

        var r = rows[0];
        return new SchemaSnapshot((string)r["fingerprint"]!, Text(r["dump"]), Utc(r["captured_at"]), (string?)r["head_chain_id"]);
    }

    /// <summary>"TREK_" for state schema "trek".</summary>
    public static string Prefix(string schema) =>
        SchemaRegex().IsMatch(schema) ? schema.ToUpperInvariant() + "_" : throw new MigrationException($"Invalid state schema name '{schema}'. Use letters, digits and underscores, starting with a letter.");

    /// <summary>The schema trek deploys to, which holds the state tables.</summary>
    internal static string Owner(IDatabaseSession session) =>
        session is OracleSession oracle ? oracle.Schema : throw new ArgumentException("Not an Oracle session.", nameof(session));

    internal static string Quote(string name) => "\"" + name.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    private static string Qualifier(IDatabaseSession session) => Quote(Owner(session)) + ".";

    private static string T(IDatabaseSession session, string schema, string table) => Qualifier(session) + Prefix(schema) + table;

    private static Dictionary<string, object?> ChangeParameters(AppliedChange change) => new()
    {
        ["name"] = change.Name,
        ["script_hash"] = change.ScriptHash,
        ["chain_id"] = change.ChainId,
        ["deploy_script"] = change.DeployScript,
        ["revert_script"] = change.RevertScript,
        ["verify_script"] = change.VerifyScript,
        ["flags"] = change.Flags,
        ["deployed_at"] = change.DeployedAtUtc,
        ["deployed_by"] = change.DeployedBy,
        ["host"] = change.Host,
        ["tool_version"] = change.ToolVersion,
        ["duration_ms"] = change.DurationMs,
        ["applied_out_of_order"] = change.AppliedOutOfOrder,
        ["baselined"] = change.Baselined,
        ["rendered_hash"] = change.RenderedHash,
        ["rendered_revert_hash"] = change.RenderedRevertHash,
    };

    private static string Text(object? value) => value as string ?? string.Empty;

    private static long Long(object? value) => Convert.ToInt64(value, CultureInfo.InvariantCulture);

    private static DateTimeOffset Utc(object? value) => value switch
    {
        DateTime d => new DateTimeOffset(DateTime.SpecifyKind(d, DateTimeKind.Utc)),
        DateTimeOffset d => d.ToUniversalTime(),
        _ => throw new InvalidCastException($"Unexpected timestamp value {value}."),
    };

    // Oracle names are at most 128 bytes; the longest suffix is "SCHEMA_SNAPSHOTS".
    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_]{0,99}$")]
    private static partial Regex SchemaRegex();
}

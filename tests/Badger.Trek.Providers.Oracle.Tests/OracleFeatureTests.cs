using System.Text.Json.Nodes;
using Badger.Trek.Core;
using Badger.Trek.Core.Providers;

namespace Badger.Trek.Providers.Oracle.Tests;

[Collection("oracle")]
public sealed class OracleFeatureTests(OracleFixture fixture)
{
    private const string Schema = """
        CREATE TABLE customer (
          id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email VARCHAR2(200 CHAR) NOT NULL UNIQUE,
          created TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
        );
        CREATE TABLE orders (
          id NUMBER(10) NOT NULL,
          customer_id NUMBER(10) NOT NULL,
          total NUMBER(12,2) DEFAULT 0 NOT NULL,
          note CLOB,
          CONSTRAINT pk_orders PRIMARY KEY (id),
          CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id) ON DELETE CASCADE,
          CONSTRAINT ck_total CHECK (total >= 0)
        );
        CREATE INDEX ix_orders_customer ON orders (customer_id, total DESC);
        CREATE INDEX ix_customer_email_lower ON customer (LOWER(email));
        CREATE SEQUENCE invoice_no START WITH 5000 INCREMENT BY 1;
        COMMENT ON TABLE orders IS 'what people bought';
        CREATE OR REPLACE VIEW big_orders AS SELECT o.id, c.email FROM orders o JOIN customer c ON c.id = o.customer_id WHERE o.total > 100;
        CREATE OR REPLACE PACKAGE shop AS
          FUNCTION order_count(p_customer NUMBER) RETURN NUMBER;
        END shop;
        /
        CREATE OR REPLACE PACKAGE BODY shop AS
          FUNCTION order_count(p_customer NUMBER) RETURN NUMBER IS
            v NUMBER;
          BEGIN
            SELECT COUNT(*) INTO v FROM orders WHERE customer_id = p_customer;
            RETURN v;
          END;
        END shop;
        /
        CREATE OR REPLACE TRIGGER orders_bi BEFORE INSERT ON orders FOR EACH ROW
        BEGIN
          IF :NEW.total IS NULL THEN
            :NEW.total := 0;
          END IF;
        END;
        /
        CREATE SYNONYM purchases FOR orders;
        """;

    private readonly OracleProvider provider = new();

    private async Task<TestSchema> RequireSchemaAsync(string? extraGrants = null)
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        return await fixture.CreateSchemaAsync(extraGrants);
    }

    private async Task RunAsync(IDatabaseSession session, string script)
    {
        foreach (var batch in provider.Parser.Split(script))
        {
            await session.ExecuteAsync(batch.Text, null, CancellationToken.None);
        }
    }

    [SkippableFact]
    public async Task The_journal_lives_in_the_schema_as_prefixed_tables()
    {
        await using var db = await RequireSchemaAsync();
        await using var session = await provider.OpenSessionAsync(db.Profile, SessionContext.Empty, CancellationToken.None);
        Assert.False(await provider.StateStore.ExistsAsync(session, "trek", CancellationToken.None));
        await provider.StateStore.EnsureCreatedAsync(session, "trek", CancellationToken.None);
        await provider.StateStore.EnsureCreatedAsync(session, "trek", CancellationToken.None);
        Assert.True(await provider.StateStore.ExistsAsync(session, "trek", CancellationToken.None));

        var tables = (await session.QueryAsync("SELECT table_name AS t FROM user_tables ORDER BY table_name", null, CancellationToken.None)).Select(r => (string)r["t"]!).ToList();
        Assert.Equal(["TREK_CHANGES", "TREK_EVENTS", "TREK_META", "TREK_REPEATABLES", "TREK_SCHEMA_SNAPSHOTS"], tables);

        var at = new DateTimeOffset(2026, 11, 20, 8, 30, 0, 123, TimeSpan.FromHours(-6));
        var longScript = "-- " + new string('x', 10_000) + "\nSELECT 1 FROM dual;";
        await provider.StateStore.InsertChangeAsync(session, "trek", new AppliedChange
        {
            Name = "c1", ScriptHash = "h", ChainId = "c", DeployScript = longScript, RevertScript = string.Empty, Flags = 2, DeployedAtUtc = at,
            DeployedBy = "me", Host = "box", ToolVersion = "1", DurationMs = 7, AppliedOutOfOrder = true, Baselined = false,
        }, CancellationToken.None);
        var change = Assert.Single(await provider.StateStore.GetAppliedChangesAsync(session, "trek", CancellationToken.None));
        Assert.Equal(at, change.DeployedAtUtc);
        Assert.Equal(TimeSpan.Zero, change.DeployedAtUtc.Offset);
        Assert.Equal(longScript, change.DeployScript);
        Assert.Equal(2, change.Flags);
        Assert.True(change.AppliedOutOfOrder);

        await provider.StateStore.SetMetaAsync(session, "trek", "environment", "a", CancellationToken.None);
        await provider.StateStore.SetMetaAsync(session, "trek", "environment", "b", CancellationToken.None);
        Assert.Equal("b", await provider.StateStore.GetMetaAsync(session, "trek", "environment", CancellationToken.None));

        await provider.StateStore.AppendEventAsync(session, "trek", new MigrationEvent { Kind = MigrationEventKind.Deploy, Name = "c1", AtUtc = at, Actor = "me", Host = "box", ToolVersion = "1" }, CancellationToken.None);
        Assert.Equal("c1", Assert.Single(await provider.StateStore.GetEventsAsync(session, "trek", 5, CancellationToken.None)).Name);

        // The state tables (and the lock table) are not part of the schema fingerprint.
        await using (await provider.Lock.AcquireAsync(session, "trek", TimeSpan.FromSeconds(5), CancellationToken.None))
        {
        }

        Assert.Equal(string.Empty, await provider.Schema.CaptureAsync(session, "trek", CancellationToken.None));
    }

    [SkippableFact]
    public async Task The_fingerprint_covers_the_schema_and_not_its_name_or_generated_names()
    {
        await using var a = await RequireSchemaAsync();
        await using var b = await RequireSchemaAsync();
        var dumps = new List<string>();
        foreach (var db in new[] { a, b })
        {
            await using var session = await provider.OpenSessionAsync(db.Profile, SessionContext.Empty, CancellationToken.None);
            await RunAsync(session, Schema);
            await session.ExecuteAsync("INSERT INTO customer (email) VALUES ('ada@example.com')", null, CancellationToken.None);
            dumps.Add(await provider.Schema.CaptureAsync(session, "trek", CancellationToken.None));
        }

        Assert.Equal(dumps[0], dumps[1]);
        Assert.DoesNotContain(a.Name, dumps[0], StringComparison.Ordinal);
        Assert.DoesNotContain("SYS_C", dumps[0], StringComparison.Ordinal);
        Assert.DoesNotContain("ISEQ$$", dumps[0], StringComparison.Ordinal);
        var keys = provider.Schema.Parse(dumps[0]).Select(e => e.Key).ToList();
        Assert.Equal(keys.Count, keys.Distinct().Count());
        Assert.Contains("column ORDERS.TOTAL", keys);
        Assert.Contains("constraint ORDERS.FK_ORDERS_CUSTOMER", keys);
        Assert.Contains("constraint ORDERS.CK_TOTAL", keys);
        Assert.Contains("index ORDERS.IX_ORDERS_CUSTOMER", keys);
        Assert.Contains("identity CUSTOMER.ID", keys);
        Assert.Contains("sequence INVOICE_NO", keys);
        Assert.Contains("view BIG_ORDERS", keys);
        Assert.Contains("source package body SHOP", keys);
        Assert.Contains("trigger ORDERS.ORDERS_BI", keys);
        Assert.Contains("synonym PURCHASES", keys);
        Assert.Contains("comment ORDERS", keys);
        Assert.Contains(dumps[0].Split('\n'), l => l.StartsWith("index|CUSTOMER|IX_CUSTOMER_EMAIL_LOWER|", StringComparison.Ordinal) && l.Contains("LOWER(\"EMAIL\")", StringComparison.Ordinal));

        await using var changed = await provider.OpenSessionAsync(b.Profile, SessionContext.Empty, CancellationToken.None);
        foreach (var (sql, key) in new[]
        {
            ("ALTER TABLE orders MODIFY (total DEFAULT 1)", "column ORDERS.TOTAL"),
            ("ALTER TRIGGER orders_bi DISABLE", "trigger ORDERS.ORDERS_BI"),
            ("CREATE OR REPLACE PACKAGE BODY shop AS FUNCTION order_count(p_customer NUMBER) RETURN NUMBER IS BEGIN RETURN 0; END; END shop;", "source package body SHOP"),
            ("ALTER SEQUENCE invoice_no INCREMENT BY 2", "sequence INVOICE_NO"),
        })
        {
            var before = provider.Schema.Parse(await provider.Schema.CaptureAsync(changed, "trek", CancellationToken.None)).Single(e => e.Key == key).Text;
            await changed.ExecuteAsync(sql, null, CancellationToken.None);
            var after = provider.Schema.Parse(await provider.Schema.CaptureAsync(changed, "trek", CancellationToken.None)).Single(e => e.Key == key).Text;
            Assert.NotEqual(before, after);
        }

        // Drawing from a sequence is data, not schema.
        var current = await provider.Schema.CaptureAsync(changed, "trek", CancellationToken.None);
        await changed.QueryAsync("SELECT invoice_no.NEXTVAL FROM dual", null, CancellationToken.None);
        Assert.Equal(current, await provider.Schema.CaptureAsync(changed, "trek", CancellationToken.None));
    }

    [SkippableFact]
    public async Task Doctor_describes_the_server()
    {
        await using var db = await RequireSchemaAsync();
        await using var session = await provider.OpenSessionAsync(db.Profile, SessionContext.Empty, CancellationToken.None);
        var facts = (await provider.DescribeAsync(session, CancellationToken.None)).ToDictionary(kv => kv.Key, kv => kv.Value);
        Assert.StartsWith("Oracle", facts["server"], StringComparison.Ordinal);
        Assert.DoesNotContain("not supported", facts["server"], StringComparison.Ordinal);
        Assert.Equal(db.Name, facts["login"]);
        Assert.Equal(db.Name, facts["schema"]);
        Assert.Equal("no", facts["encrypted"]);
    }

    [SkippableFact]
    public async Task A_deploy_login_can_deploy_to_another_schema()
    {
        await using var app = await RequireSchemaAsync();
        await using var deployer = await RequireSchemaAsync("CREATE ANY TABLE, DROP ANY TABLE, ALTER ANY TABLE, SELECT ANY TABLE, INSERT ANY TABLE, UPDATE ANY TABLE, DELETE ANY TABLE, LOCK ANY TABLE, CREATE ANY INDEX, CREATE ANY VIEW, CREATE ANY SEQUENCE, SELECT ANY SEQUENCE, SELECT ANY DICTIONARY");
        var profile = deployer.Profile with { ProviderSettings = new JsonObject { ["schema"] = app.Name.ToLowerInvariant() } };
        Assert.Equal(app.Name, provider.ResolveDatabaseName(profile));

        await using var session = await provider.OpenSessionAsync(profile, SessionContext.Empty, CancellationToken.None);
        Assert.Contains($"as {app.Name}", session.Description, StringComparison.Ordinal);
        await provider.StateStore.EnsureCreatedAsync(session, "trek", CancellationToken.None);
        await session.ExecuteAsync("CREATE TABLE widget (id NUMBER PRIMARY KEY)", null, CancellationToken.None);
        await using (await provider.Lock.AcquireAsync(session, "trek", TimeSpan.FromSeconds(5), CancellationToken.None))
        {
            var owners = (await session.QueryAsync("SELECT owner, table_name FROM all_tables WHERE table_name IN ('WIDGET', 'TREK_CHANGES', 'TREK_LOCK') ORDER BY table_name", null, CancellationToken.None))
                .Select(r => $"{r["owner"]}.{r["table_name"]}").ToList();
            Assert.Equal([$"{app.Name}.TREK_CHANGES", $"{app.Name}.TREK_LOCK", $"{app.Name}.WIDGET"], owners);
        }

        Assert.Contains("table|WIDGET|", await provider.Schema.CaptureAsync(session, "trek", CancellationToken.None), StringComparison.Ordinal);

        var missing = deployer.Profile with { ProviderSettings = new JsonObject { ["schema"] = "NO_SUCH_SCHEMA_X" } };
        var error = await Assert.ThrowsAsync<MigrationException>(() => provider.OpenSessionAsync(missing, SessionContext.Empty, CancellationToken.None));
        Assert.Contains("does not exist", error.Message, StringComparison.Ordinal);
    }

    [SkippableFact]
    public async Task Scripts_with_plsql_sqlplus_settings_and_exec_run_as_sqlplus_would()
    {
        await using var db = await RequireSchemaAsync();
        await using var session = await provider.OpenSessionAsync(db.Profile, SessionContext.Empty, CancellationToken.None);
        await RunAsync(session, """
            SET DEFINE OFF
            PROMPT creating
            CREATE TABLE log_entry (id NUMBER GENERATED ALWAYS AS IDENTITY, msg VARCHAR2(100), at TIMESTAMP DEFAULT SYSTIMESTAMP);
            CREATE OR REPLACE PROCEDURE log_it(p_msg VARCHAR2) AS
            BEGIN
              INSERT INTO log_entry (msg) VALUES (p_msg);
            END;
            /
            EXEC log_it('R&D; done')
            DECLARE
              v NUMBER;
            BEGIN
              SELECT COUNT(*) INTO v FROM log_entry;
              IF v <> 1 THEN
                RAISE_APPLICATION_ERROR(-20001, 'expected one row');
              END IF;
            END;
            /
            """);
        Assert.Equal("R&D; done", (await session.QueryAsync("SELECT msg FROM log_entry", null, CancellationToken.None))[0]["msg"]);
    }

using Badger.SqlMigrate.Core.Configuration;
using Badger.SqlMigrate.Core.Providers;
using Badger.SqlMigrate.Providers.PostgreSql.Scripting;

namespace Badger.SqlMigrate.Providers.PostgreSql.Tests;

/// <summary>
/// Round trips: deploy must turn database A into a schema-identical copy of B, and revert must turn it back.
/// "Identical" is the schema fingerprint dump, so this also proves the generated SQL is complete.
/// </summary>
[Collection("postgresql")]
public sealed class ScripterTests(PostgreSqlFixture fixture)
{
    private readonly PostgreSqlProvider provider = new();

    private const string Base = """
        CREATE SCHEMA sales;
        CREATE TYPE public.mood AS ENUM ('sad', 'ok');
        CREATE DOMAIN public.phone AS varchar(20) CHECK (VALUE ~ '^[0-9+ ]+$');
        CREATE TYPE public.pair AS (x int, y int);
        CREATE SEQUENCE public.seq AS integer START WITH 1 INCREMENT BY 1;
        CREATE TABLE public.customer (
            id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) PRIMARY KEY,
            name text NOT NULL,
            email varchar(100),
            old integer,
            code char(3) NOT NULL DEFAULT 'ABC',
            mood public.mood);
        COMMENT ON TABLE public.customer IS 'People who buy';
        COMMENT ON COLUMN public.customer.name IS 'Full name';
        CREATE TABLE public."order" (
            id integer PRIMARY KEY,
            customer_id integer NOT NULL CONSTRAINT fk_order_customer REFERENCES public.customer (id),
            total numeric(10, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
            note text DEFAULT '{x}');
        CREATE INDEX ix_order_customer ON public."order" (customer_id);
        CREATE TABLE public.gone (id integer NOT NULL, payload text);
        CREATE TABLE public.event (at date NOT NULL, id integer NOT NULL) PARTITION BY RANGE (at);
        CREATE TABLE public.event_2026 PARTITION OF public.event FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
        CREATE FUNCTION public.order_total(cid integer) RETURNS numeric LANGUAGE sql STABLE AS $$ SELECT sum(total) FROM public."order" WHERE customer_id = cid $$;
        CREATE VIEW public.v_customer AS SELECT id, name FROM public.customer;
        CREATE PROCEDURE public.p_old() LANGUAGE plpgsql AS $$ BEGIN END $$;
        DO $$ BEGIN CREATE ROLE bsm_reader NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
        GRANT SELECT ON public.customer TO bsm_reader;
        """;

    private const string Edits = """
        ALTER TABLE public.customer ALTER COLUMN email TYPE varchar(200);
        ALTER TABLE public.customer ADD COLUMN phone public.phone, ADD COLUMN created timestamptz NOT NULL DEFAULT now();
        DROP VIEW public.v_customer;
        ALTER TABLE public.customer DROP COLUMN old;
        ALTER TABLE public.customer RENAME COLUMN code TO country_code;
        ALTER TYPE public.mood ADD VALUE 'happy' AFTER 'ok';
        COMMENT ON TABLE public.customer IS 'People who buy things';
        COMMENT ON COLUMN public.customer.name IS NULL;
        ALTER TABLE public."order" DROP CONSTRAINT fk_order_customer;
        ALTER TABLE public."order" ALTER COLUMN total TYPE numeric(19, 4);
        ALTER TABLE public."order" ADD CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES public.customer (id) ON DELETE CASCADE;
        DROP INDEX public.ix_order_customer;
        CREATE INDEX ix_order_customer ON public."order" (customer_id, id);
        CREATE INDEX ix_order_total ON public."order" (total DESC) INCLUDE (customer_id) WHERE total > 0;
        DROP TABLE public.gone;
        CREATE TABLE sales.region (
            code char(2) PRIMARY KEY,
            name text NOT NULL UNIQUE,
            label text GENERATED ALWAYS AS (code || '-' || name) STORED);
        ALTER TABLE public."order" ADD COLUMN region_code char(2) REFERENCES sales.region (code);
        CREATE TABLE public.event_2027 PARTITION OF public.event FOR VALUES FROM ('2027-01-01') TO ('2028-01-01');
        CREATE INDEX ix_event_id ON public.event (id);
        ALTER SEQUENCE public.seq INCREMENT BY 5;
        CREATE SEQUENCE sales.ticket AS bigint START WITH 1000 CACHE 50;
        ALTER TYPE public.pair ADD ATTRIBUTE z int;
        DROP PROCEDURE public.p_old();
        CREATE OR REPLACE FUNCTION public.order_total(cid integer) RETURNS numeric LANGUAGE sql STABLE AS $$ SELECT coalesce(sum(total), 0) FROM public."order" WHERE customer_id = cid $$;
        CREATE VIEW public.v_customer AS SELECT id, name, email FROM public.customer;
        CREATE VIEW public.v_totals AS SELECT id, public.order_total(id) AS total FROM public.v_customer;
        CREATE FUNCTION public.touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.note := 'touched'; RETURN NEW; END $$;
        CREATE TRIGGER tr_order BEFORE INSERT ON public."order" FOR EACH ROW EXECUTE FUNCTION public.touch();
        ALTER TABLE public."order" ENABLE ROW LEVEL SECURITY;
        CREATE POLICY p_all ON public."order" USING (true);
        GRANT SELECT ON public."order" TO bsm_reader;
        REVOKE SELECT ON public.customer FROM bsm_reader;
        GRANT UPDATE (email) ON public.customer TO bsm_reader;
        """;

    [SkippableFact]
    public async Task Deploy_turns_a_into_b_and_revert_turns_it_back()
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        await using var a = await fixture.CreateDatabaseAsync();
        await using var b = await fixture.CreateDatabaseAsync();
        await RunAsync(a, Base);
        await RunAsync(b, Base);
        await RunAsync(b, Edits);
        var before = await DumpAsync(a);
        var target = await DumpAsync(b);

        var script = await ScriptAsync(a, b);
        var backwards = await ScriptAsync(b, a);

        Assert.Contains(script.Summary, s => s == "~ column public.customer.code renamed to country_code");
        Assert.Contains(script.Summary, s => s == "- table public.gone");
        Assert.Contains(script.Summary, s => s == "+ table sales.region");
        Assert.Contains(script.Summary, s => s.StartsWith("~ column public.\"order\".total: numeric(10,2) -> numeric(19,4)", StringComparison.Ordinal));
        Assert.True(script.DataLoss);
        Assert.Contains(script.Warnings, w => w.Contains("drops table public.gone", StringComparison.Ordinal));

        await RunAsync(a, script.Deploy, script);
        Assert.Equal(target, await DumpAsync(a));

        var again = await ScriptAsync(a, b);
        Assert.Equal(string.Empty, again.Deploy);

        // Enum values cannot be removed while columns use the type: revert says so instead of scripting it.
        Assert.Contains(backwards.Warnings, w => w.Contains("cannot remove or reorder enum values", StringComparison.Ordinal));
        await RunAsync(a, script.Revert, script);
        await RunAsync(a, "ALTER TYPE public.mood RENAME TO mood_x; CREATE TYPE public.mood AS ENUM ('sad', 'ok'); ALTER TABLE public.customer ALTER COLUMN mood TYPE public.mood USING mood::text::public.mood; DROP TYPE public.mood_x;");
        Assert.Equal(WithoutColumnPositions(before), WithoutColumnPositions(await DumpAsync(a)));
    }

    private static string WithoutColumnPositions(string dump) =>
        string.Join('\n', dump.Split('\n').Select(l => System.Text.RegularExpressions.Regex.Replace(l, @"^column\|([^|]*)\|\d+\|", "column|$1|#|")).Order(StringComparer.Ordinal));

    [SkippableFact]
    public async Task Changing_a_function_signature_rebuilds_what_uses_it()
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        await using var a = await fixture.CreateDatabaseAsync();
        await using var b = await fixture.CreateDatabaseAsync();
        const string table = "CREATE TABLE public.t (id integer PRIMARY KEY, qty integer NOT NULL);\n";
        await RunAsync(a, table + """
            CREATE FUNCTION public.twice(v integer) RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT v * 2';
            CREATE VIEW public.v AS SELECT id, public.twice(qty) AS q FROM public.t;
            CREATE INDEX ix_t_twice ON public.t (public.twice(qty));
            ALTER TABLE public.t ADD CONSTRAINT ck_twice CHECK (public.twice(qty) < 100);
            """);
        await RunAsync(b, table + """
            CREATE FUNCTION public.twice(v integer) RETURNS bigint LANGUAGE sql IMMUTABLE AS 'SELECT v::bigint * 2';
            CREATE VIEW public.v AS SELECT id, public.twice(qty) AS q FROM public.t;
            CREATE INDEX ix_t_twice ON public.t (public.twice(qty));
            ALTER TABLE public.t ADD CONSTRAINT ck_twice CHECK (public.twice(qty) < 100);
            """);

        var script = await ScriptAsync(a, b);
        await RunAsync(a, script.Deploy, script);
        Assert.Equal(await DumpAsync(b), await DumpAsync(a));
        await RunAsync(a, script.Revert, script);
        Assert.Equal(string.Empty, (await ScriptAsync(a, a)).Deploy);
    }

    [SkippableFact]
    public async Task Repeatable_objects_and_journal_tables_are_left_out()
    {
        Skip.If(fixture.AdminConnectionString is null, fixture.UnavailableReason);
        await using var a = await fixture.CreateDatabaseAsync();
        await using var b = await fixture.CreateDatabaseAsync();
        await RunAsync(a, "CREATE TABLE public.t (id integer NOT NULL);\nCREATE VIEW public.v AS SELECT id FROM public.t;");
        await RunAsync(b, "CREATE TABLE public.t (id integer NOT NULL, name integer);\nCREATE VIEW public.v AS SELECT id, name FROM public.t;\nCREATE TABLE public.flyway_schema_history (installed_rank integer NOT NULL);\nCREATE SCHEMA bsm;\nCREATE TABLE bsm.changes (x integer);");

        await using var from = await SessionAsync(a);
        await using var to = await SessionAsync(b);
        var script = await provider.Scripter.ScriptAsync(from, to, new SchemaScriptOptions
        {
            StateSchema = "bsm",
            Exclude = ["*.flyway_schema_history"],
            RepeatableScripts = ["-- view\nCREATE OR REPLACE VIEW public.\"v\" AS SELECT 1 AS x;"],
        }, CancellationToken.None);

        Assert.Equal(["+ column public.t.name integer"], script.Summary);
        Assert.Contains(script.Warnings, w => w.Contains("view public.v is defined by a repeatable script", StringComparison.Ordinal));
    }

    [Fact]
    public void Repeatable_scripts_own_the_routines_they_create()
    {
        var owned = PostgreSqlScripter.OwnedRoutines([
            "CREATE OR REPLACE VIEW public.vA AS SELECT 1;",
            "create function \"Sales\".\"fn B\"() returns int language sql as 'select 1'",
            "CREATE MATERIALIZED VIEW IF NOT EXISTS mv AS SELECT 1;",
            "CREATE PROCEDURE p() LANGUAGE sql AS 'SELECT 1';",
            "-- CREATE TABLE public.not_a_routine (id int)",
        ]);
        Assert.True(owned.SetEquals(["public.va", "Sales.fn B", "public.mv", "public.p"]), string.Join(", ", owned));
    }

    private async Task<SchemaScript> ScriptAsync(TestDatabase from, TestDatabase to)
    {
        await using var a = await SessionAsync(from);
        await using var b = await SessionAsync(to);
        return await provider.Scripter.ScriptAsync(a, b, new SchemaScriptOptions { StateSchema = "bsm" }, CancellationToken.None);
    }

    private async Task<string> DumpAsync(TestDatabase db)
    {
        await using var session = await SessionAsync(db);
        return await provider.Schema.CaptureAsync(session, "bsm", CancellationToken.None);
    }

    /// <summary>Runs a script in one transaction, as a change would.</summary>
    private async Task RunAsync(TestDatabase db, string sql, SchemaScript? context = null)
    {
        await using var session = await SessionAsync(db);
        await session.BeginTransactionAsync(CancellationToken.None);
        foreach (var batch in provider.Parser.Split(sql))
        {
            try
            {
                await session.ExecuteBatchAsync(batch, CancellationToken.None);
            }
            catch (Exception ex) when (ex is not OutOfMemoryException)
            {
                throw new InvalidOperationException($"{ex.Message}\n--- statement ---\n{batch.Text}\n--- script ---\n{sql}{(context is null ? string.Empty : "\n--- summary ---\n" + string.Join('\n', context.Summary))}", ex);
            }
        }

        await session.CommitAsync(CancellationToken.None);
    }

    private Task<IDatabaseSession> SessionAsync(TestDatabase db) => provider.OpenSessionAsync(db.Profile, SessionContext.Empty, CancellationToken.None);
}

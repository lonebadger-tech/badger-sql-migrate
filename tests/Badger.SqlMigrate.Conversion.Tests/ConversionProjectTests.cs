using Badger.SqlMigrate.Core.Conversion;
using Xunit.Abstractions;

namespace Badger.SqlMigrate.Conversion.Tests;

public class ConversionProjectTests(ITestOutputHelper output)
{
    private void Dump(ConversionResult result)
    {
        foreach (var c in result.Project.Changes)
        {
            output.WriteLine($"=== {c.Name}\n{c.Deploy}\n--- revert\n{c.Revert}");
        }

        foreach (var r in result.Project.Repeatables)
        {
            output.WriteLine($"=== repeatable/{r.Path}\n{r.Script}");
        }

        output.WriteLine(result.Report);
    }

    [Fact]
    public void SqlServer_to_PostgreSql_tables()
    {
        var schema = Schemas.SqlServer();
        schema.Tables.Add(new PortableTable(new PortableName("dbo", "CustomerOrder"),
            [
                new PortableColumn("OrderId", "bigint", false) { Identity = new PortableIdentity(1000, 1, false) },
                new PortableColumn("CustomerId", "int", false),
                new PortableColumn("Code", "varchar(20)", true),
                new PortableColumn("Total", "decimal(12,2)", false) { Default = "((0))" },
                new PortableColumn("TotalWithTax", "decimal(13,2)", true) { Computed = "([Total]*(1.2))", ComputedStored = true },
            ],
            new PortableKey("PK_CustomerOrder", ["OrderId"]),
            [new PortableKey("UQ_CustomerOrder_Code", ["Code"])],
            [],
            [new PortableForeignKey("FK_CustomerOrder_Customer", ["CustomerId"], new PortableName("dbo", "Customer"), ["CustomerId"], "CASCADE", "NO ACTION")],
            [new PortableIndex("IX_Customer", false, [new PortableIndexColumn("CustomerId", false, false)], ["Total"], "([Code] IS NOT NULL)", null)]));
        var result = ConversionProject.Build(schema, new ConversionOptions { TargetProvider = "postgresql", Names = NameStyle.Snake });
        Dump(result);
        var tables = result.Project.Changes.Single(c => c.Name == "convert-tables").Deploy;
        Assert.Contains("customer_id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL", tables);
        Assert.Contains("first_name varchar(50) COLLATE public.bsm_ci NOT NULL", tables);
        Assert.Contains("is_active boolean DEFAULT true NOT NULL", tables);
        Assert.Contains("total_with_tax numeric(13,2) GENERATED ALWAYS AS (total * (1.2)) STORED", tables);
        Assert.Contains("CONSTRAINT ck_balance CHECK (balance >= (0))", tables);
        Assert.Contains("CREATE COLLATION IF NOT EXISTS public.bsm_ci", result.Project.Changes.Single(c => c.Name == "convert-types").Deploy);
        Assert.Contains("REFERENCES public.customer (customer_id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE", result.Project.Changes.Single(c => c.Name == "convert-foreign-keys").Deploy);
        Assert.Contains("CREATE INDEX ix_customer ON public.customer_order (customer_id) INCLUDE (total) WHERE code IS NOT NULL;", result.Project.Changes.Single(c => c.Name == "convert-indexes").Deploy);
    }

    [Fact]
    public void PostgreSql_to_SqlServer_tables()
    {
        var result = ConversionProject.Build(Schemas.Postgres(), new ConversionOptions { TargetProvider = "sqlserver" });
        Dump(result);
        var tables = result.Project.Changes.Single(c => c.Name == "convert-tables").Deploy;
        Assert.Contains("id bigint IDENTITY(1, 1) NOT NULL", tables);
        Assert.Contains("status nvarchar(7) CONSTRAINT DF_orders_status DEFAULT (N'new') NOT NULL", tables);
        Assert.Contains("paid bit CONSTRAINT DF_orders_paid DEFAULT (0) NOT NULL", tables);
        Assert.Contains("CHECK (status IN (N'new', N'paid', N'shipped'))", tables);
        Assert.Contains("CHECK (ISJSON(tags) = 1)", tables);
        Assert.Contains("CHECK (total >= 0)", tables);
    }
}
